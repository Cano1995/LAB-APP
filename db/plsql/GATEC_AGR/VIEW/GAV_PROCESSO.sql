CREATE OR REPLACE VIEW GATEC_AGR.GAV_PROCESSO AS
(SELECT LPAD(P.COD_PROCESSO, 5, 0) || '00000000000000000000000' ID_PROC,
		  NULL ID_PAI,
		  P.COD_PROCESSO COD_PROC,
		  LTRIM(RTRIM(P.DSC_PROCESSO)) DSC_PROC,
		  1 PRO_NIVEL,
      0 AS ID_S4,
		  CONTA PRO_QTDFILHOS
 FROM   GA_PROCESSO P,
		  (SELECT COD_PROCESSO,
					 COUNT(*) CONTA
			FROM   GA_SUBPROCESSO
			GROUP  BY COD_PROCESSO) C
 WHERE  P.COD_PROCESSO = C.COD_PROCESSO
 UNION
	 SELECT LPAD(SP.COD_PROCESSO, 5, 0) || LPAD(SP.COD_SUBPROCESSO, 5, 0) ||
			  '000000000000000000' ID_PROC,
			  LPAD(SP.COD_PROCESSO, 5, 0) || '00000000000000000000000' ID_PAI,
			  SP.COD_SUBPROCESSO COD_PROC,
			  LTRIM(RTRIM(SP.DSC_SUBPROCESSO)) DSC_PROC,
			  2 PRO_NIVEL,
        0 AS ID_S4,
			  CONTA PRO_QTDFILHOS
	 FROM   GA_PROCESSO P,
			  GA_SUBPROCESSO SP,
			  (SELECT COD_PROCESSO,
						 COD_SUBPROCESSO,
						 COUNT(*) CONTA
				FROM   GA_GRUPO_OPERACAO
				GROUP  BY COD_PROCESSO,
							 COD_SUBPROCESSO) C
	 WHERE  P.COD_PROCESSO = SP.COD_PROCESSO AND
			  C.COD_PROCESSO = SP.COD_PROCESSO AND
			  C.COD_SUBPROCESSO = SP.COD_SUBPROCESSO
	 UNION
		 SELECT LPAD(GR.COD_PROCESSO, 5, 0) || LPAD(GR.COD_SUBPROCESSO, 5, 0) ||
				  LPAD(GR.COD_GRUPO_OPER, 5, 0) || '0000000000000' ID_PROC,
				  LPAD(GR.COD_PROCESSO, 5, 0) || LPAD(GR.COD_SUBPROCESSO, 5, 0) ||
				  '000000000000000000' ID_PAI,
				  GR.COD_GRUPO_OPER COD_PROC,
				  LTRIM(RTRIM(GR.DSC_GRUPO_OPER)) DSC_PROC,
				  3 PRO_NIVEL,
          0 AS ID_S4,
				  C.CONTA PRO_QTDFILHOS
		 FROM   GA_PROCESSO P,
				  GA_SUBPROCESSO SP,
				  GA_GRUPO_OPERACAO GR,
				  (SELECT COD_PROCESSO,
							 COD_SUBPROCESSO,
							 COD_GRUPO_OPER,
							 COUNT(*) CONTA
					FROM   GA_OPERACAO_AGRICOLA
					GROUP  BY COD_PROCESSO,
								 COD_SUBPROCESSO,
								 COD_GRUPO_OPER) C
		 WHERE  P.COD_PROCESSO = GR.COD_PROCESSO AND
				  SP.COD_PROCESSO = GR.COD_PROCESSO AND
				  SP.COD_SUBPROCESSO = GR.COD_SUBPROCESSO AND
				  C.COD_PROCESSO = GR.COD_PROCESSO AND
				  C.COD_SUBPROCESSO = GR.COD_SUBPROCESSO AND
				  C.COD_GRUPO_OPER = GR.COD_GRUPO_OPER
		 UNION
			 SELECT LPAD(OA.COD_PROCESSO, 5, 0) ||
					  LPAD(OA.COD_SUBPROCESSO, 5, 0) ||
					  LPAD(OA.COD_GRUPO_OPER, 5, 0) || 
            LPAD(OA.ID_OPER, 5, 0) || LPAD(OA.ID_S4,8,0) ID_PROC,
					  LPAD(OA.COD_PROCESSO, 5, 0) ||
					  LPAD(OA.COD_SUBPROCESSO, 5, 0) ||
					  LPAD(OA.COD_GRUPO_OPER, 5, 0) || '0000000000000' ID_PAI,
					  OA.ID_OPER COD_PROC,
					  LTRIM(RTRIM(TB.DSC_OPER)) DSC_PROC,
					  4 PRO_NIVEL,
            ID_S4 AS ID_S4,
					  0 PRO_QTDFILHOS
			 FROM   GA_OPERACAO_AGRICOLA OA,
					  GA_PROCESSO P,
					  GA_SUBPROCESSO SP,
					  GA_GRUPO_OPERACAO GR,
					  GA_TABGR_OPER_AGRIC TB
			 WHERE  P.COD_PROCESSO = OA.COD_PROCESSO AND
					  SP.COD_PROCESSO = OA.COD_PROCESSO AND
					  SP.COD_SUBPROCESSO = OA.COD_SUBPROCESSO AND
					  GR.COD_PROCESSO = OA.COD_PROCESSO AND
					  GR.COD_SUBPROCESSO = OA.COD_SUBPROCESSO AND
					  GR.COD_GRUPO_OPER = OA.COD_GRUPO_OPER AND
					  TB.ID_OPER = OA.ID_OPER)

 
/
