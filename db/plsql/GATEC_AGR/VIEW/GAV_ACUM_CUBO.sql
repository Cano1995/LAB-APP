CREATE OR REPLACE VIEW GATEC_AGR.GAV_ACUM_CUBO AS
SELECT A.SAF_ANO_SAFRA,
       A.COD_EMPR,
       TO_CHAR(D1.COD_DIVI1) || '-' || D1.ABV_DIVI1 AS DIVI1,
       TO_CHAR(D2.COD_DIVI2) || '-' || D2.ABV_DIVI2 AS DIVI2,
       TO_CHAR(D3.COD_DIVI3) || '-' || D3.ABV_DIVI3 AS DIVI3,
       D4.COD_DIVI4,
       D4.COD_ESTAG_USINA,
       VU.ABV_VARIE,
       SU.ABV_SOLO,
       SU.SOL_AMBIENTE,
       'SEM MUNIC' MUN_MUNIC,
       case when tipo_persona = 'N' then 'TERCERO' else 'AZPA' end  FAG_NOME,
       DECODE( D4.DI4_SITUA,
              0,
              'SEM COLHEITA PREVISTA',
              1,
              'PREV. P/ COLHE. EM AREA PARCIAL',
              2,
              'PREV. P/ COLHE. EM AREA TOTAL',
              3,
              'AUTORIZADO PARA COLHEITA',
              4,
              'EM PROCESSO DE COLHEITA',
              5,
              'ENCERRADO PARCIALMENTE',
              6,
              'AREA ENCERRADA TOTAL') AS SITUACAO,
       TC.ABV_TIP_CORTE,
       A.AC_DT_ACUM,
       case when cod_tipo_liq = 1 then 'ORGANICA' else 'CONVENCIONAL' end  COD_FRENTE,
       TO_CHAR(AC_DT_ACUM, 'MM/YYYY') DT_ACUM_M,
       A.AC_PROD / 1000 AS PRODUCAO,
       A.AC_PROD_ANALI / 1000 AS PRODUCAO_ANALI,
       0 as AREA,
       --A.AC_AREA_colhida AS AREA,
       --(A.AC_PROD / 1000) / A.AC_AREA_colhida AS TCH,
       0 as tch,
       DECODE(NVL(A.AC_POND_BRIX, 0), 0, 0, A.AC_PROD / 1000) AS PRODUCAO_BRIX,
       DECODE(NVL(A.AC_POND_POL_CANA, 0), 0, 0, A.AC_PROD / 1000) AS PRODUCAO_POL,
       DECODE(NVL(A.AC_POND_TEMP_QUEI, 0), 0, 0, A.AC_PROD / 1000) AS PRODUCAO_TQ,
       DECODE(NVL(A.AC_POND_TEMP_CORTE, 0), 0, 0, A.AC_PROD / 1000) AS PRODUCAO_TC,
       NVL(A.AC_POND_BRIX, 0) * (A.AC_PROD / 1000) AS BRIX,
       NVL(A.AC_POND_BRIX, 0) * (A.AC_PROD / 1000) /
       DECODE(NVL(A.AC_POND_BRIX, 0), 0, 1, A.AC_PROD / 1000) brix_calc,
       NVL(A.AC_POND_LS, 0) * (A.AC_PROD / 1000) AS LS,
       NVL(A.AC_POND_PBU, 0) * (A.AC_PROD / 1000) AS PBU,
       NVL(A.AC_POND_AR, 0) * (A.AC_PROD / 1000) AS AR,
       NVL(A.AC_POND_POL_CALDO, 0) * (A.AC_PROD / 1000) AS POL_CALDO,
       NVL(A.AC_POND_POL_CANA, 0) * (A.AC_PROD / 1000) AS POL_CANA,
       NVL(A.AC_POND_PUREZA, 0) * (A.AC_PROD / 1000) AS PUREZA,
       NVL(A.AC_POND_FIBRA, 0) * (A.AC_PROD / 1000) AS FIBRA,
       NVL(A.AC_POND_ATR, 0) * (A.AC_PROD / 1000) AS ATR,
       NVL(A.AC_POND_TEMP_CORTE, 0) * (A.AC_PROD / 1000) AS TC,
       NVL(A.AC_POND_TEMP_QUEI, 0) * (A.AC_PROD / 1000) AS TQ,
       ltrim(rtrim(TO_CHAR(D1.COD_DIVI1))) persona_id,
       ltrim(rtrim(TO_CHAR(D2.COD_DIVI2))) finca
 FROM GA_ACUM_D4     A,
       GA_DIVI1       D1,
       GA_DIVI2       D2,
       GA_DIVI3       D3,
       GA_DIVI4       D4,
       GA_VARIE_DIVI4 VD,
       GA_VARIE_USINA VU,
       GA_TIPO_CORTE  TC,
       GA_SOLOS_DIVI4 SD,
       GA_SOLOS_USINA SU
 WHERE NVL(A.AC_PROD, 0) > 0
   AND D1.SAF_ANO_SAFRA = A.SAF_ANO_SAFRA
   AND D1.COD_EMPR = A.COD_EMPR
   AND D1.COD_DIVI1 = A.COD_DIVI1
   AND D2.SAF_ANO_SAFRA = A.SAF_ANO_SAFRA
   AND D2.COD_EMPR = A.COD_EMPR
   AND D2.COD_DIVI1 = A.COD_DIVI1
   AND D2.COD_DIVI2 = A.COD_DIVI2
   AND D3.SAF_ANO_SAFRA = A.SAF_ANO_SAFRA
   AND D3.COD_EMPR = A.COD_EMPR
   AND D3.COD_DIVI1 = A.COD_DIVI1
   AND D3.COD_DIVI2 = A.COD_DIVI2
   AND D3.COD_DIVI3 = A.COD_DIVI3
   AND D4.SAF_ANO_SAFRA = A.SAF_ANO_SAFRA
   AND D4.COD_EMPR = A.COD_EMPR
   AND D4.COD_DIVI1 = A.COD_DIVI1
   AND D4.COD_DIVI2 = A.COD_DIVI2
   AND D4.COD_DIVI3 = A.COD_DIVI3
   AND D4.COD_DIVI4 = A.COD_DIVI4
   AND VD.ID_DIVI4 = D4.ID_DIVI4
   AND VU.COD_VARIE_USINA = VD.COD_VARIE_USINA
   AND TC.COD_TIP_CORTE = A.COD_TIP_CORTE
   AND SD.ID_DIVI4 = D4.ID_DIVI4
   AND SU.COD_SOLO_USINA = SD.COD_SOLO_USINA

 
/
