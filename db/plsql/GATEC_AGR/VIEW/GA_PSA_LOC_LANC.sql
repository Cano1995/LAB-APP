CREATE OR REPLACE VIEW GATEC_AGR.GA_PSA_LOC_LANC AS
SELECT LA.SAF_ANO_SAFRA, LA.COD_EMPR, 
LA.COD_RECUR_LANC, 
LA.LANC_DT_ABERT, 
LA.LANC_DT_ENCERR,
LO.ID_DIVI4, 
LO.LOC_AREA,
AV.ID_S4, AV.ID_OPER 
FROM GA_RECUR_UTIL_LANC LA,
GA_RECUR_UTIL_LOC LO,
GA_RECUR_UTIL_ATIV AV
WHERE LO.ID_RECUR_LANC=LA.ID_RECUR_LANC AND
AV.ID_RECUR_LANC=LA.ID_RECUR_LANC AND
TO_NUMBER(TO_CHAR(LA.LANC_DT_ABERT, 'YYYY')) = LA.SAF_ANO_SAFRA

 
/
