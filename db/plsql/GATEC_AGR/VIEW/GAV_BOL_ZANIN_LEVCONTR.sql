CREATE OR REPLACE VIEW GATEC_AGR.GAV_BOL_ZANIN_LEVCONTR AS
SELECT LA.COD_EMPR, LA.SAF_ANO_SAFRA, LA.LANC_DATA,
       OP.COD_PROCESSO, OP.COD_SUBPROCESSO, OP.COD_GRUPO_OPER, OP.ID_OPER,
       FR.COD_FRENTE, FR.DSC_FRENTE, LO.ID_DIVI4, SUM(DISTINCT LO.LOC_AREA) AS LOC_AREA
FROM GA_PRD_LANC LA,
     GA_PRD_LOC LO,
     GA_PRD_ATIV AV,
     GA_OPERACAO_AGRICOLA OP,
     GA_FRENT_TRABA FR
WHERE LO.ID_RECUR_LANC=LA.ID_RECUR_LANC AND
      AV.ID_RECUR_LANC=LA.ID_RECUR_LANC AND
      OP.ID_S4=AV.ID_S4 AND
      FR.COD_FRENTE=LA.COD_FRENTE
GROUP BY LA.COD_EMPR, LA.SAF_ANO_SAFRA, LA.LANC_DATA,
       OP.COD_PROCESSO, OP.COD_SUBPROCESSO, OP.COD_GRUPO_OPER, OP.ID_OPER,
       FR.COD_FRENTE, FR.DSC_FRENTE, LO.ID_DIVI4

 
